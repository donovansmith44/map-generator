-- <someStyle> / <someOtherStyle>: two styles that are DISTINCT BY
-- CONSTRUCTION.
--
-- Not `suchThat (/=)` (rejection sampling, which is distinctness by
-- retry — correct, but it makes "can these ever collide?" a question
-- about the sampler's luck rather than about the generator's codomain),
-- and emphatically not "draw twice and hope". Draw one style, then
-- rotate by a NON-ZERO offset in Z_n: `i` and `i + d` are different
-- residues for every `d` in 1..n-1, so no draw this generator can
-- produce has the two equal. The distinctness test over a run of
-- iterations is then pinning a property the construction already
-- guarantees, which is exactly the right relationship between a law and
-- its test.
--
-- Requires at least two dresses to exist at all (a "different style"
-- is not a thing you can ask for in a one-style world) — pinned as its
-- own test rather than left as an implicit assumption of the modulus.
genStylePair :: Gen (StyleName, StyleName)
genStylePair = do
  i <- chooseInt (0, n - 1)
  d <- chooseInt (1, n - 1)
  pure (styleAt i, styleAt (i + d))
  where
    n = length styleNames
    styleAt k = StyleName (styleNames !! (k `mod` n))

-- <someSubset> / <someSuperset>: a NESTED pair, by construction.
--
-- Draw the superset first, then draw the subset from INSIDE it, so
-- `subset ⊆ superset` holds for every draw this generator can produce —
-- there is no draw in its codomain that violates the nesting, so the
-- subtractive law never spends an iteration red for a reason that has
-- nothing to do with the server.
--
-- Equality (subset == superset) is a LEGAL draw and is deliberately not
-- excluded: `fewer ⊆ more` is a claim about ⊆, and the reflexive case is
-- part of what it claims. But a law tested only on equal sets tests
-- nothing about subtraction, so the DISTRIBUTION matters as much as the
-- codomain: `sublistOf` keeps each of the superset's k pieces
-- independently, so the two coincide with probability 2^-k, and
-- averaging over the superset's own sublistOf draw gives
-- (3/2)^10 / 2^10 ≈ 5.6% — i.e. roughly 94% of draws are PROPER
-- subsets. The distribution test pins a floor of a quarter: far below
-- what the construction actually delivers (so it is not a threshold
-- tuned to today's numbers), far above zero (so a future change that
-- collapsed the pair into equality would fail it loudly).
genNestedPieces :: Gen (PieceSet, PieceSet)
genNestedPieces = do
  PieceSet super <- genPieces
  sub <- sublistOf (Set.toList super)
  pure (PieceSet (Set.fromList sub), PieceSet super)

