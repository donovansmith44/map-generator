-- ---------- holes, drawn in CORRELATED GROUPS ----------
--
-- A hole is not always independent of its neighbours. Three of this
-- corpus's laws are about a RELATIONSHIP between two drawn values, and
-- they are vacuous unless the draw establishes it:
--
--   * dress-locality quantifies over <someStyle> and <someOtherStyle>.
--     Two independent draws from the three styles collide one time in
--     three, and a "restyle" to the SAME style leaves the two bodies
--     identical, which the step then reports as "dress did not actually
--     change" -- a red that says nothing about the server.
--   * the subtractive law quantifies over <someSubset> and
--     <someSuperset>. Two independent piece sets are nested only by
--     luck; the law would spend most of its iterations red for a reason
--     that is not a fact about the server either.
--
-- The trap this project has already fallen into once (fix 7cd31bd:
-- someA/someB drew the IDENTICAL value from one iteration-only seed, so
-- the composition law degenerated to `x == x ∪ x` and could not fail) is
-- the same trap seen from the other side. Correlation by ACCIDENT made a
-- law unfalsifiable; correlation on PURPOSE makes these laws checkable —
-- and the difference between the two is entirely whether the
-- relationship is declared, generated by construction, and pinned by a
-- test that would fail if it broke. So correlation is a first-class
-- thing here, not a special case in the substitution code:
--
-- A GROUP is the unit of drawing. Its members are drawn TOGETHER, from
-- ONE seed, by ONE generator that establishes whatever relationship
-- holds between them. An ordinary independent hole is the degenerate
-- group of one (`solo`), so there is a single drawing rule, not two.
data HoleGroup = HoleGroup
  { groupName    :: Text
    -- ^ the group's own identity — what its seed is keyed on. For a solo
    -- group this IS the hole's name, so solo holes keep the exact seeds
    -- (and therefore the exact draws) they had before groups existed.
  , groupMembers :: [Text]
    -- ^ every hole name this group binds. Must be disjoint from every
    -- other group's (pinned as a law: `holeRegistry` is a partition).
  , groupDraw    :: Gen (Map Text Text)
    -- ^ ONE draw, producing the rendered binding for every member at
    -- once. Rendering (rather than a typed existential) happens inside
    -- the generator because that is where the members' types are still
    -- known; a group can mix types freely without the registry needing
    -- to know about it.
  , groupShrink  :: Map Text Text -> [Map Text Text]
    -- ^ Spec §4's other half of a hole's contract: from the bindings a
    -- failing iteration actually used, the strictly smaller bindings
    -- worth trying instead. The GROUP is the unit here for the same
    -- reason it is the unit of drawing -- a candidate that re-bound only
    -- half of a correlated pair could hand the law a binding no draw
    -- could ever have produced, and a counterexample that is not an
    -- example of anything is worse than a large one. So a candidate
    -- replaces EVERY member at once and owes `groupLaw` below, exactly
    -- as `groupDraw` does.
    --
    -- Rendered in, rendered out: candidates are derived from the CURRENT
    -- values (parse -> shrink -> re-render), never from a fresh draw, so
    -- shrinking consumes no randomness and the same failing run always
    -- walks the same path to the same minimum.
  , groupRank    :: Map Text Text -> Int
    -- ^ How BIG this group's bindings are, as a natural number. Every
    -- candidate `groupShrink` offers must have a strictly smaller rank
    -- than the bindings it came from; since the rank is a bounded
    -- natural, no sequence of shrinks can go on forever, and none can
    -- return to a value it has already left. That is what makes the
    -- greedy loop terminate -- see `shrinkToMinimal`, where the fuel
    -- bound is then a backstop against a mis-written shrinker rather
    -- than the thing that ends a normal run.
  , groupLaw     :: Map Text Text -> Bool
    -- ^ The relationship this group establishes, as a predicate over
    -- rendered bindings. Declared on the group rather than restated in
    -- the test file so that a NEW correlated group cannot be added
    -- without saying what it correlates -- the relationship is then owed
    -- by the generator and the shrinker alike, and one test pins both.
    -- `const True` for a solo group, which establishes nothing.
  }

-- What it means for one of a group's drawn values to be SMALLER, as one
-- value rather than two loose functions: a shrinking ORDER is a rank
-- together with the candidates it admits, and the pairing is the whole
-- content of the contract ("every candidate ranks strictly lower"). Kept
-- together so a shrinker cannot be written, or changed, without saying
-- what it is shrinking WITH RESPECT TO -- which is exactly the step the
-- first draft of this task skipped, and it cost a real cycle: -1405 and
-- -1400 each offered the other, and only the fuel bound stopped the
-- loop (see `yearRank`).
data Order a = Order
  { rankOf     :: a -> Int
  , shrinkWith :: a -> [a]
  }

-- The degenerate group: one hole, drawn on its own, exactly as before,
-- and shrunk on its own -- a solo group correlates nothing, so its law
-- is trivially true and its candidates are just its member's.
solo :: FromCapture a => Text -> Gen a -> Order a -> HoleGroup
solo n g o = soloLawful n g o (const True)

-- A solo group WITH a law. A group of one correlates nothing with a
-- partner, but it can still owe a property of its own -- <someZoom>
-- does: the two cameras camera.feature derives from it ("doubled",
-- "halved") must be other cameras, or the laws quantified over it
-- compare a scene with itself. `solo` is this at `const True`, so
-- there is still ONE drawing rule and one shrinking rule, not two, and
-- the generic pins (every draw and every candidate satisfies its
-- group's law) reach a lawful solo group for free.
soloLawful :: FromCapture a => Text -> Gen a -> Order a -> (Map Text Text -> Bool) -> HoleGroup
soloLawful n g o lawful = HoleGroup n [n] (Map.singleton n . renderCap <$> g) sh rk lawful
  where
    sh env = [ Map.singleton n r
             | Right a <- [bound1 n env], a' <- shrinkWith o a, r <- renderLawful a' ]
    -- An unreadable binding ranks 0 and shrinks to nothing: it is the
    -- bottom of the order in both, so the two answers agree instead of
    -- one of them quietly claiming progress the other cannot make.
    rk env = either (const 0) (rankOf o) (bound1 n env)

-- A two-member correlated group: ONE generator produces both values, so
-- whatever relation it establishes between them is true BY CONSTRUCTION
-- of every draw, not true on average or true after a retry -- and ONE
-- shrinker produces both replacements, so the same is true of every
-- candidate.
pair :: (FromCapture a, FromCapture b)
     => Text -> Text -> Text
     -> Gen (a, b) -> Order (a, b) -> (Map Text Text -> Bool)
     -> HoleGroup
pair gname n1 n2 g o lawful = HoleGroup gname [n1, n2] draw sh rk lawful
  where
    draw = rend <$> g
    rend (a, b) = Map.fromList [(n1, renderCap a), (n2, renderCap b)]
    both env = (,) <$> bound1 n1 env <*> bound1 n2 env
    sh env = [ Map.fromList [(n1, r1), (n2, r2)]
             | Right ab <- [both env], (x, y) <- shrinkWith o ab
             , r1 <- renderLawful x, r2 <- renderLawful y ]
    rk env = either (const 0) (rankOf o) (both env)

-- A correlated pair whose members ALSO mean something on their own.
--
-- `pair` above is the right shape when the two holes only ever appear
-- together: with a partner missing, `both` fails, so the group offers no
-- candidates and ranks 0 -- it simply does not shrink. That costs
-- nothing for <someStyle>/<someOtherStyle> (dresses have no candidates
-- to offer in the first place) and nothing for
-- <someSubset>/<someSuperset> (which the corpus only ever writes
-- together).
--
-- It costs a great deal for <someYear>. The step phase had to move
-- `someYear` into a correlated pair with `someOtherYear`, because the
-- span laws (transition's four, and subjects' span-vs-instant) are
-- degenerate or falsely red when the two years collide -- and a
-- collision is not hypothetical at 1 draw in 4104. But <someYear> is
-- also the corpus's most-used hole, appearing ALONE in eight scenarios
-- across scene, census, subjects and resources, and its shrinker (the
-- one that walks a failing year down to the -1405 landmark, and whose
-- well-foundedness cost this project a real cycle to get right) is the
-- diagnosis those scenarios lean on. Registering the pair with `pair`
-- would have silently deleted it from all eight.
--
-- So: when both members are in evidence, this behaves exactly like
-- `pair` -- one correlated draw, one correlated candidate, the pair's
-- own order. When only ONE is (because the scenario mentions only one),
-- it behaves exactly like `solo` on that member, using the member's own
-- order. Nothing is re-bound that the scenario did not mention, and a
-- candidate is still confined, still strictly smaller, and still owes
-- `groupLaw` -- see `shrinkToMinimalWith`'s gates, which now admit a
-- half-present group precisely because a relation with an absent
-- partner is not a relation that can be broken (`distinctPairLaw`
-- states that side of it).
--
-- `pair` is NOT re-expressed in terms of this: its partial-env
-- behaviour (rank 0, no candidates) is a deliberate statement about
-- holes that mean nothing alone, and collapsing the two would turn that
-- statement into an accident of which order was passed.
pairOrSolo :: forall a. (FromCapture a, Eq a)
           => Text -> Text -> Text
           -> Gen (a, a) -> Order (a, a) -> Order a -> (Map Text Text -> Bool)
           -> HoleGroup
pairOrSolo gname n1 n2 g o o1 lawful = HoleGroup gname [n1, n2] draw sh rk lawful
  where
    draw = rend <$> g
    rend (a, b) = Map.fromList [(n1, renderCap a), (n2, renderCap b)]
    sh env = case slice env of
      Just (Left (a, b)) -> [ Map.fromList [(n1, r1), (n2, r2)]
                            | (x, y) <- shrinkWith o (a, b)
                            , r1 <- renderLawful x, r2 <- renderLawful y ]
      Just (Right (n, a)) -> [ Map.singleton n r
                             | a' <- shrinkWith o1 a, r <- renderLawful a' ]
      Nothing -> []
    rk env = case slice env of
      Just (Left ab)      -> rankOf o ab
      Just (Right (_, a)) -> rankOf o1 a
      Nothing             -> 0
    -- Which members this environment carries, read back through the very
    -- captures the corpus parses them with. `Left` is the correlated
    -- case (both present), `Right` the solo one (exactly one present,
    -- named so the candidate re-binds the right hole); `Nothing` is
    -- either nothing present at all or a present binding that does not
    -- read back -- both bottoms of the order, which is the honest answer
    -- for a value we cannot examine.
    slice :: Map Text Text -> Maybe (Either (a, a) (Text, a))
    slice env = case (Map.lookup n1 env, Map.lookup n2 env) of
      (Just _, Just _) -> either (const Nothing) (Just . Left)
                            ((,) <$> bound1 @a n1 env <*> bound1 @a n2 env)
      (Just _, Nothing) -> fmap (Right . (,) n1) (eitherToMaybe (bound1 @a n1 env))
      (Nothing, Just _) -> fmap (Right . (,) n2) (eitherToMaybe (bound1 @a n2 env))
      (Nothing, Nothing) -> Nothing
    eitherToMaybe = either (const Nothing) Just

-- One hole's current binding, parsed back through the very capture the
-- corpus parses it with. Parsing back is what keeps a shrinker honest in
-- both directions: a value it cannot read is not a value it may shrink,
-- and a rendering that does not parse is not a candidate.
bound1 :: FromCapture a => Text -> Map Text Text -> Either Text a
bound1 n env =
  maybe (Left ("no binding for " <> n)) Right (Map.lookup n env) >>= parseCap

-- The other half of that discipline, and the ONE gate a shrink candidate
-- passes to become a binding: a candidate is offered as text only if its
-- rendering survives the round trip its own capture will put it through
-- at substitution time. A value the corpus cannot read back is not a
-- smaller counterexample, it is a broken one -- and the step that would
-- have consumed it reports an obscure capture error naming the capture
-- rather than the shrinker.
--
-- This is also why no `Order` states a type's FRAME. Year's -4004..100,
-- and the fact that year 0 does not exist in this calendar, are declared
-- exactly once -- in `Capture.parseCap` -- and every order, present and
-- future, inherits them here for free instead of restating them and
-- drifting. An order says what SMALLER means; the capture says what
-- LEGAL means; neither has to know the other's business.
renderLawful :: forall a. FromCapture a => a -> [Text]
renderLawful a = [ r | Right (_ :: a) <- [parseCap r] ]
  where r = renderCap a

-- A possibly-empty subset of every piece. R6/the scene's own algebra:
-- the empty scene is the monoid identity, and `sublistOf` genuinely
-- includes `[]` in its codomain, so the identity IS reachable here —
-- see the "genPieces can generate the empty piece set" test, which
-- samples this generator directly to prove it, not just trust the docs.
genPieces :: Gen PieceSet
genPieces = PieceSet . Set.fromList <$> sublistOf [minBound .. maxBound]

